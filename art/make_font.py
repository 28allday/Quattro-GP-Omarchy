# The sheet runs from space to '_' inclusive: 64 codes, four rows of sixteen.
FIRST, LAST = 32, 95


def main():
    rows = (LAST - FIRST + 1 + COLS - 1) // COLS
    img = Image.new("RGBA", (COLS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    px = img.load()

    drawn = 0
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        pat = G.get(ch)
        if not pat:
            continue
        i = code - FIRST
        ox, oy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        for r, line in enumerate(pat.split("|")):
            for c, bit in enumerate(line):
                if bit == "#":
                    px[ox + c, oy + r] = (255, 255, 255, 255)
        drawn += 1

    img.save(os.path.join(HERE, "font.png"))
    missing = [chr(c) for c in range(FIRST, LAST + 1)
               if chr(c) not in G and chr(c) != " "]
    print(f"font.png {img.width}x{img.height}  {drawn} glyphs")
    if missing:
        print("undefined (render as blanks):", "".join(missing))


if __name__ == "__main__":
    main()
